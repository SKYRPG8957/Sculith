#!/usr/bin/env python3
"""Generate a compile-checked packet registration list from pinned bedrock-rs.

Only packet type identifiers are copied. IDs/metadata resolve through the actual
locked Rust associated types at compilation. Unknown packets remain explicit.
"""
import argparse
from pathlib import Path
import re
import subprocess

REVISION = "5221fcae8cc8468f523f3f58f129cb308e9d3369"

def generate(source):
    actual=subprocess.check_output(["git","-C",str(source),"rev-parse","HEAD"],text=True).strip()
    if actual!=REVISION:raise ValueError("Expected the locked bedrock-rs source")
    path=source/"crates/protocol/src/generated/v2225.rs"
    code=path.read_text(encoding="utf-8")
    body=code[code.index("pub enum V2225 {"):code.index("    impl bedrock_protocol_core::Packets")]
    variants=re.findall(r"^        (\w+)\(",body,re.MULTILINE)
    if len(variants)!=len(set(variants)) or variants.count("Unknown")!=1:
        raise ValueError("Invalid packet registration input")
    variants.remove("Unknown")
    return ("// Generated by scripts/generate_bedrock_packet_catalog.py.\n"
            f"// bedrock-rs {REVISION}, protocol 2225; names only.\n"
            "registered_packets!(\n"+"".join(f"    {name},\n" for name in variants)+");\n")

if __name__=="__main__":
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source",type=Path,required=True)
    parser.add_argument("--output",type=Path,required=True)
    args=parser.parse_args();text=generate(args.source.resolve(strict=True))
    args.output.parent.mkdir(parents=True,exist_ok=True)
    args.output.write_text(text,encoding="utf-8")
    print("Generated",text.count("Packet,"),"typed native registrations",args.output)
